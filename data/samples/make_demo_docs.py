# ---------- 3. 常见问题.txt ----------
txt_content = """公司常用问题解答手册

一、工资发放相关
问：工资什么时候发？
答：每月十号发放上月工资，如遇节假日提前至最近的工作日。工资条会在发放当天通过 OA 系统推送。

问：工资由哪几部分构成？
答：基本工资、岗位工资和绩效奖金三部分。具体金额见个人工资条，如有疑问可联系人力资源部。

问：新员工第一个月工资怎么算？
答：按实际出勤天数折算，计算公式为月工资除以当月应出勤天数乘以实际出勤天数。

二、请假与考勤相关
问：怎么请假？
答：在 OA 系统提交请假申请，病假需附医院证明，事假每月累计不超过三天。三天以内由部门主管审批，三天以上需主管和人力资源部共同审批。

问：迟到了怎么办？
答：迟到超过十五分钟记为一次迟到，每月累计三次以上影响当月绩效。因公外出需提前提交外出申请。

问：年假有几天？
答：工作满一年享五天带薪年假，每增加一年增加一天，上限十五天。

三、报销与办公相关
问：报销流程是什么？
答：在 OA 系统填写报销单，附上发票照片，部门主管审批后由财务部打款，一般五个工作日内到账。

问：办公用品在哪里领？
答：行政部统一发放，每月初可申请一次，紧急需求可随时联系行政部同事。

四、培训与晋升相关
问：新员工要参加什么培训？
答：入职第一周参加入职培训，内容包括公司文化、规章制度和岗位职责，由人力资源部组织。

问：晋升通道是怎样的？
答：公司实行双通道晋升，管理通道从专员到总监，专业通道从初级到资深专家，每年两次晋升评审。

五、其他常见问题
问：离职流程怎么走？
答：提前三十天提交书面离职申请，完成工作交接和资料归还后办理离职手续，工资在离职当月结清。
"""
